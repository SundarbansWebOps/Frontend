export function dateRangeLabel(event, formatDate) {
  if (!event.start) return event.detail ?? 'Date yet to be decided';
  const from = formatDate(event.start);
  return event.end && event.end !== event.start ? `${from} – ${formatDate(event.end)}` : from;
}
